"""Offline place lookups over a compact GeoNames table.

The data files in ``data/`` are generated by ``tools/build_gazetteer.py`` from
the GeoNames dump (cities15000, countryInfo, admin1CodesASCII; CC BY 4.0).
Tables are streamed line by line instead of being loaded into indexes, so a
lookup costs a few megabytes of transient buffers rather than a resident
in-memory map of every place name.
"""

from __future__ import annotations

import math
import re
import unicodedata
from datetime import datetime
from pathlib import Path
from typing import Iterable, Iterator, NamedTuple, Optional

DATA_DIR = Path(__file__).resolve().parent.parent / "data"

EARTH_RADIUS_KM = 6371.0

# Names that are real places but far too generic to be evidence on their own:
# a sign reading "CENTRAL" does not locate an image.
STOP_ALIASES = frozenset({
    "central", "center", "centre", "north", "south", "east", "west", "upper",
    "lower", "new town", "old town", "main", "market", "national", "park",
    "beach", "harbour", "harbor", "airport", "station", "university", "city",
    "town", "village", "street", "road", "square", "hotel", "river", "lake",
})

_PUNCT = re.compile(r"[^\w\- ]", re.UNICODE)
_SPACES = re.compile(r"\s+", re.UNICODE)


class City(NamedTuple):
    id: int
    name: str
    lat: float
    lon: float
    cc: str
    admin1: str
    pop: int
    tz: str


class Region(NamedTuple):
    code: str
    name: str
    lat: float
    lon: float


class Country(NamedTuple):
    cc: str
    name: str
    continent: str
    lat: float
    lon: float


def normalize_alias(text: str) -> str:
    """Fold a place name or OCR token into the form stored in aliases.tsv."""
    folded = unicodedata.normalize("NFKD", text.casefold())
    folded = "".join(ch for ch in folded if not unicodedata.combining(ch))
    folded = re.sub(r"['\u2019`\u00b4]", "", folded)
    folded = _PUNCT.sub(" ", folded)
    folded = folded.replace("-", " ").replace("_", " ")
    return _SPACES.sub(" ", folded).strip()


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = phi2 - phi1
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * EARTH_RADIUS_KM * math.asin(min(1.0, math.sqrt(a)))


def _rows(name: str, data_dir: Path) -> Iterator[list[str]]:
    path = data_dir / name
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if parts and parts[0]:
                yield parts


def iter_cities(data_dir: Path = DATA_DIR) -> Iterator[City]:
    for parts in _rows("cities.tsv", data_dir):
        if len(parts) < 8:
            continue
        yield City(
            int(parts[0]), parts[1], float(parts[2]), float(parts[3]),
            parts[4], parts[5], int(parts[6]), parts[7],
        )


def find_city_ids(phrases: Iterable[str], data_dir: Path = DATA_DIR) -> dict[int, list[str]]:
    """Map geonameid -> matched aliases for the given normalized phrases."""
    wanted = {p for p in phrases if p and p not in STOP_ALIASES}
    if not wanted:
        return {}
    hits: dict[int, list[str]] = {}
    for parts in _rows("aliases.tsv", data_dir):
        if len(parts) < 2:
            continue
        if parts[0] in wanted:
            hits.setdefault(int(parts[1]), []).append(parts[0])
    return hits


def cities_by_id(ids: Iterable[int], data_dir: Path = DATA_DIR) -> dict[int, City]:
    wanted = set(ids)
    if not wanted:
        return {}
    found: dict[int, City] = {}
    for city in iter_cities(data_dir):
        if city.id in wanted:
            found[city.id] = city
    return found


def nearest(lat: float, lon: float, limit: int = 1, data_dir: Path = DATA_DIR) -> list[tuple[City, float]]:
    import heapq

    best: list[tuple[float, int, City]] = []
    for city in iter_cities(data_dir):
        distance = haversine_km(lat, lon, city.lat, city.lon)
        if len(best) < limit:
            heapq.heappush(best, (-distance, city.id, city))
        elif distance < -best[0][0]:
            heapq.heapreplace(best, (-distance, city.id, city))
    return [(city, -neg) for neg, _, city in sorted(best, key=lambda item: -item[0])]


def load_countries(data_dir: Path = DATA_DIR) -> dict[str, Country]:
    countries: dict[str, Country] = {}
    for parts in _rows("countries.tsv", data_dir):
        if len(parts) < 5:
            continue
        countries[parts[0]] = Country(parts[0], parts[1], parts[2], float(parts[3]), float(parts[4]))
    return countries


def load_regions(data_dir: Path = DATA_DIR) -> dict[str, Region]:
    regions: dict[str, Region] = {}
    for parts in _rows("admin1.tsv", data_dir):
        if len(parts) < 4:
            continue
        regions[parts[0]] = Region(parts[0], parts[1], float(parts[2]), float(parts[3]))
    return regions


def country_name(cc: str, data_dir: Path = DATA_DIR) -> str:
    return load_countries(data_dir).get(cc, Country(cc, cc, "", 0.0, 0.0)).name


def region_name(code: str, data_dir: Path = DATA_DIR) -> str:
    if not code:
        return ""
    return load_regions(data_dir).get(code, Region(code, "", 0.0, 0.0)).name


def region_lon_center(hours: float) -> float:
    """Longitude a UTC offset of ``hours`` nominally corresponds to."""
    return (hours * 15.0 + 180.0) % 360.0 - 180.0


def tz_offsets(zones: Iterable[str], when: Optional[datetime] = None) -> dict[str, float]:
    """UTC offset in hours for each IANA zone at the given local time."""
    try:
        from zoneinfo import ZoneInfo
    except ImportError:  # pragma: no cover - Python < 3.9
        return {}
    reference = when or datetime.now()
    offsets: dict[str, float] = {}
    for zone in zones:
        try:
            delta = ZoneInfo(zone).utcoffset(reference)
        except (KeyError, ValueError, OSError):
            # Unknown zone or missing tzdata: skip it and let the caller fall
            # back to longitude bands.
            continue
        if delta is not None:
            offsets[zone] = delta.total_seconds() / 3600.0
    return offsets


def cities_in_offset_band(
    hours: float,
    when: Optional[datetime] = None,
    tolerance: float = 1.0,
    limit: int = 40,
    data_dir: Path = DATA_DIR,
) -> list[City]:
    """Cities whose local UTC offset matches, ranked by population."""
    zones = {city.tz for city in iter_cities(data_dir) if city.tz}
    offsets = tz_offsets(zones, when)

    matches: list[City] = []
    if offsets:
        for city in iter_cities(data_dir):
            offset = offsets.get(city.tz)
            if offset is not None and abs(offset - hours) <= tolerance:
                matches.append(city)
    else:
        # Without tzdata, fall back to the 15 degrees-per-hour longitude band.
        center = hours * 15.0
        for city in iter_cities(data_dir):
            delta = abs((city.lon - center + 180.0) % 360.0 - 180.0)
            if delta <= tolerance * 15.0:
                matches.append(city)

    matches.sort(key=lambda city: city.pop, reverse=True)
    return matches[:limit]


class NePlace(NamedTuple):
    """A Natural Earth populated place, used as an independent second opinion."""

    name: str
    lat: float
    lon: float
    cc: str
    region: str
    pop: int
    tz: str


def ne_places_available(data_dir: Path = DATA_DIR) -> bool:
    return (data_dir / "places_ne.tsv").is_file()


def match_ne_places(
    phrases: Iterable[str], data_dir: Path = DATA_DIR
) -> list[tuple[NePlace, list[str]]]:
    """Stream Natural Earth places whose names appear in ``phrases``."""
    wanted = {phrase for phrase in phrases if phrase and phrase not in STOP_ALIASES}
    if not wanted or not ne_places_available(data_dir):
        return []
    matches: list[tuple[NePlace, list[str]]] = []
    for parts in _rows("places_ne.tsv", data_dir):
        if len(parts) < 8:
            continue
        matched = [alias for alias in parts[0].split("|") if alias in wanted]
        if not matched:
            continue
        matches.append((
            NePlace(
                parts[1], float(parts[2]), float(parts[3]), parts[4],
                parts[5], int(parts[6]), parts[7],
            ),
            matched,
        ))
    return matches
